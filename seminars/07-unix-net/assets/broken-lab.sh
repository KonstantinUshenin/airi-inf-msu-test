#!/usr/bin/env bash
# Учебный стенд к задаче H1: поднимает несколько сервисов, часть из которых
# намеренно сломана разными способами, и печатает список адресов для проверки.
#
#   ./broken-lab.sh start   — поднять стенд и показать список целей
#   ./broken-lab.sh stop    — снять стенд и освободить порты
#   ./broken-lab.sh answers — показать, что именно сломано (только после отчёта!)
#
# Прав администратора не требует: все поломки воспроизводятся без фаервола.

set -u

LAB_DIR="$HOME/seminar-07/lab"
PID_FILE="$LAB_DIR/pids"

# Внешний адрес машины — берём из маршрута, а не глазами.
ext_ip() {
    ip route get 8.8.8.8 2>/dev/null | grep -oP 'src \K\S+' | head -1
}

serve() {   # serve <порт> <адрес привязки> <каталог>
    nohup python3 -m http.server "$1" --bind "$2" --directory "$3" \
        > "$LAB_DIR/log-$1.txt" 2>&1 &
    echo "$!" >> "$PID_FILE"
}

start() {
    stop_quiet
    mkdir -p "$LAB_DIR/ok" "$LAB_DIR/empty"
    : > "$PID_FILE"
    echo "сервис жив" > "$LAB_DIR/ok/health"

    serve 8101 127.0.0.1 "$LAB_DIR/ok"       # A: исправен
    serve 8104 127.0.0.1 "$LAB_DIR/ok"       # C: слушает не тот порт, что объявлен
    serve 8105 127.0.0.1 "$LAB_DIR/empty"    # D: жив, но нужного пути нет
    serve 8107 127.0.0.1 "$LAB_DIR/ok"       # F: привязан к loopback, объявлен снаружи
    sleep 1

    local ip
    ip="$(ext_ip)"
    ip="${ip:-127.0.0.1}"

    cat <<EOF
Стенд поднят. Проверьте каждую цель и поставьте диагноз:

  svc-a   http://127.0.0.1:8101/health
  svc-b   http://127.0.0.1:8102/health
  svc-c   http://127.0.0.1:8103/health
  svc-d   http://127.0.0.1:8105/health
  svc-e   http://192.0.2.1:8106/health
  svc-f   http://$ip:8107/health

Подсказка по инструментам: ss -tlnp, nc -z -v -w 3, curl -sS -m 3 -o /dev/null -w '%{http_code}'.
Снять стенд: $0 stop
EOF
}

stop_quiet() {
    [ -f "$PID_FILE" ] || return 0
    while read -r pid; do
        [ -n "$pid" ] && kill "$pid" 2>/dev/null
    done < "$PID_FILE"
    rm -f "$PID_FILE"
    sleep 1
}

stop() {
    stop_quiet
    echo "стенд снят, порты 8101–8107 свободны"
}

answers() {
    cat <<'EOF'
Разбор стенда — сверяйтесь только после сдачи отчёта.

  svc-a  исправен. Ступени пройдены все, код 200. Контрольная цель:
         если она не работает, сломан сам стенд.

  svc-b  ступень 4. На порту 8102 не запущено ничего и никогда не было.
         Симптом: мгновенный refused, в ss порта нет.
         Починка: запустить сервис.

  svc-c  ступень 4, но причина другая. Процесс есть, слушает соседний
         порт 8104, а объявлен 8103. Симптом снаружи тот же — refused,
         но ss показывает живой процесс рядом.
         Починка: исправить порт в конфигурации или в ссылке.

  svc-d  ступень 5. Сервис жив и отвечает, но файла health у него нет.
         Симптом: соединение устанавливается, код 404.
         Починка: чинить сам сервис, сеть ни при чём.

  svc-e  ступень 3. Адрес 192.0.2.1 не маршрутизируется (RFC 5737).
         Симптом: таймаут, ответа нет вообще.
         Починка: проверить адрес и маршрут, а не сервис.

  svc-f  ступень 4, ловушка адреса привязки. Сервис поднят на 8107, но
         только на loopback, а объявлен по внешнему адресу машины.
         Симптом: по внешнему адресу refused, по 127.0.0.1 — код 200.
         Починка: --bind 0.0.0.0 либо туннель (семинар 8).
EOF
}

case "${1:-start}" in
    start)   start ;;
    stop)    stop ;;
    answers) answers ;;
    *)       echo "использование: $0 {start|stop|answers}" >&2 ; exit 2 ;;
esac
