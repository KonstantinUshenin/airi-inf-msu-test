"""Генератор микро-лекции семинара 10 (`demo.ipynb`).

Ноутбук собирается из этого скрипта, а не правится руками: так удобнее
редактировать длинные markdown-блоки, а схемы из `images/` вшиваются в
ноутбук автоматически.

    python3 seminars/10-python-text/build_demo.py

ВАЖНО: правьте этот файл, а НЕ demo.ipynb — при следующем запуске скрипта
ручные правки ноутбука будут затёрты. Признак того, что ноутбук порождённый:
в его metadata стоит ключ "generated_by".
"""

import base64
import json
import pathlib


def img(name, alt):
    """SVG вшивается в ноутбук как data-URI.

    Относительные пути к картинкам ни GitHub внутри .ipynb, ни Colab не
    резолвят, а битая иллюстрация в учебном материале хуже раздутого диффа.
    Источник правды — файлы в images/, ноутбук пересобирается из них.
    """
    svg = (pathlib.Path(__file__).resolve().parent / "images" / name).read_bytes()
    b64 = base64.b64encode(svg).decode("ascii")
    return f"![{alt}](data:image/svg+xml;base64,{b64})"


C = []


def md(src):
    C.append(("markdown", src))


def code(src):
    C.append(("code", src.strip("\n")))


def q(question, answer):
    md("#### ❓ **Вопрос**: " + question + "\n\n"
       "<details>\n\n<summary><strong>Ответ</strong></summary>\n\n"
       + answer + "\n\n</details>")


def note(text):
    """Заметка преподавателя: то, что рассказывается вслух, а не читается.

    Свёрнутый блок, чтобы ноутбук не превращался в конспект: деталь или
    байка остаётся козырем ведущего, а студент разворачивает её потом,
    когда готовится к защите.
    """
    md("<details>\n\n<summary>🎙 <em>Заметка преподавателя — рассказывается вслух</em>"
       "</summary>\n\n" + text + "\n\n</details>")


