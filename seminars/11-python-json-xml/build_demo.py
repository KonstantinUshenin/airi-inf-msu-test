  "`find` возвращает **один** элемент (первый совпавший) или `None`, а "
  "`findall` — **список**, возможно пустой. Пути тоже разные: `.//` ищет на "
  "любой глубине по всему дереву, `./catalog[@kind='current']/book` — строго "
  "по указанному пути и только в каталоге с нужным атрибутом. Приведение типа "
