import pathlib

HERE = pathlib.Path(__file__).resolve().parent

cells = []


def img(name, alt):
    """SVG вшивается в ноутбук как data-URI.

    Относительные пути к картинкам GitHub внутри .ipynb не резолвит, а битая
    иллюстрация в учебном материале хуже раздутого диффа. Источник правды —
    файлы в images/, ноутбук пересобирается из них.
    """
    svg = (HERE / "images" / name).read_bytes()
    return f"![{alt}](data:image/svg+xml;base64,{base64.b64encode(svg).decode('ascii')})"


def md(text):
    cells.append({
        "cell_type": "markdown",
        "metadata": {},
        "source": text.strip("\n").splitlines(keepends=True),
    })


def code(text):
    cells.append({
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": text.strip("\n").splitlines(keepends=True),
    })


def question(q, a):
    md(
        "#### ❓ **Вопрос**: %s\n\n"
        "<details>\n\n<summary><strong>Ответ</strong></summary>\n\n"
        "%s\n\n</details>" % (q.strip(), a.strip())
    )


def note(text):
    md(
        "<details>\n\n<summary>🎙 <em>Заметка преподавателя — рассказывается вслух</em>"
        "</summary>\n\n%s\n\n</details>" % text.strip()
    )


